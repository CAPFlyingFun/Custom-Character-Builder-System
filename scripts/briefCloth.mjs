/**
 * HER BIKINI BOTTOM'S CLOTH, CUT FROM THE MODELLED BRIEF (Joshua, 2026-11-11: "MESHY model bottom with stretchy as a
 * cloth sim, but not alter the shape or design of it…").
 *
 * The brief in her body file (MeshyAI's tie-side brief, `fitMeshyBikini.mjs`) is drawn whole in the room and moved by a
 * cloth (`src/sarahlab/briefCloth.ts`, `clothBrief.ts`). Simulating all of its ~10,000 points would cost a phone's frame
 * what the whole cloth tee does, so the cloth is the brief short of its knots and bows -- both faces of its fabric --
 * simplified (meshoptimizer, its cut edge kept where it is): about a thousand points, every one a point of the brief
 * itself. This writes those triangles, in the brief's own vertex numbering, into a module the room reads.
 *
 *   node scripts/briefCloth.mjs assets-archive/models/sarah-v2-body.glb src/sarahlab/briefClothProxy.ts
 */
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder, MeshoptSimplifier } from 'meshoptimizer';
import { writeFileSync } from 'node:fs';

/** MEASURED (2026-11-11, on her body file): past 17 cm either side of her middle the brief is its knots and bows. */
export const TIE_FROM_M = 0.17;
/**
 * GAME TUNING: triangles in the cloth, and the simplifier's error bound (a share of the brief's size). At 2,000 the
 * cloth has 1,029 points and the brief's own points lie a median 0.11 mm, at most 1.9 mm, off it (2026-11-11; 3,000
 * kept 1,529 points for 0.05 mm; 1,000, 529 points but 5.6 mm off at the worst).
 */
export const CLOTH_TRIANGLES = 2000, SIMPLIFY_ERROR = 0.002;
/** GAME TUNING (layout only): base64 characters per line of the generated module. */
const LINE = 112;

const mul = (x, y) => { const o = new Array(16).fill(0); for (let c = 0; c < 4; c++) for (let r = 0; r < 4; r++) for (let k = 0; k < 4; k++) o[c * 4 + r] += x[k * 4 + r] * y[c * 4 + k]; return o; };

export async function briefCloth(glb, outFile, log = console.log) {
  await Promise.all([MeshoptDecoder.ready, MeshoptSimplifier.ready]);
  const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
  const doc = await io.read(glb);
  const skin = doc.getRoot().listSkins()[0];
  const T = mul(skin.listJoints()[0].getWorldMatrix(), Array.from(skin.getInverseBindMatrices().getArray().slice(0, 16)));
  // the brief: the 'bikini' primitive below her waist (the top's are above it)
  const prims = doc.getRoot().listMeshes()[0].listPrimitives();
  const brief = prims.find((p) => {
    if (p.getMaterial()?.getName() !== 'bikini' || !p.getIndices()) return false;
    const A = p.getAttribute('POSITION'), v = []; let top = -Infinity;
    for (const i of p.getIndices().getArray()) { A.getElement(i, v); top = Math.max(top, T[1] * v[0] + T[5] * v[1] + T[9] * v[2] + T[13]); }
    return top < 1.0;
  });
  if (!brief) throw new Error('no bikini bottom in ' + glb);
  const A = brief.getAttribute('POSITION'), n = A.getCount(), P = new Float32Array(n * 3), v = [];
  for (let i = 0; i < n; i++) { A.getElement(i, v); for (let r = 0; r < 3; r++) P[i * 3 + r] = T[r] * v[0] + T[4 + r] * v[1] + T[8 + r] * v[2] + T[12 + r]; }
  const I = brief.getIndices().getArray();
  // short of its knots and bows: every triangle with a corner this side of TIE_FROM
  const tie = (k) => Math.abs(P[k * 3]) > TIE_FROM_M, body = [];
  for (let t = 0; t < I.length; t += 3) if (!(tie(I[t]) && tie(I[t + 1]) && tie(I[t + 2]))) body.push(I[t], I[t + 1], I[t + 2]);
  const [tris, error] = MeshoptSimplifier.simplify(Uint32Array.from(body), P, 3, CLOTH_TRIANGLES * 3, SIMPLIFY_ERROR, ['LockBorder']);
  const points = new Set(tris).size;
  const bytes = new Uint8Array(new Uint16Array(tris).buffer), data = Buffer.from(bytes).toString('base64');
  const lines = []; for (let i = 0; i < data.length; i += LINE) lines.push(`    '${data.slice(i, i + LINE)}'`);
  const source = `/**
 * GENERATED by \`scripts/briefCloth.mjs\` -- do not edit by hand. To regenerate, from the repo root:
 *   node scripts/briefCloth.mjs assets-archive/models/sarah-v2-body.glb src/sarahlab/briefClothProxy.ts
 *
 * HER BIKINI BOTTOM'S CLOTH (Joshua, 2026-11-11: "MESHY model bottom with stretchy as a cloth sim, but not alter the
 * shape or design of it…"): the modelled brief in her body file short of its knots and bows (past ${TIE_FROM_M * 100} cm either side of
 * her middle), both faces of its fabric, simplified to ${tris.length / 3} triangles on ${points} of its own points (meshoptimizer,
 * its cut edge kept; error ${error.toFixed(5)} of its size). Triangles in the brief's own vertex numbering (${n} vertices),
 * three little-endian 16-bit indices each, base64.
 */
export const BRIEF_CLOTH_PROXY = Object.freeze({
  vertices: ${n},
  triangles: ${tris.length / 3},
  data:
${lines.join(' +\n')},
});

let decoded: Uint32Array | null = null;

/** The cloth's triangles (the brief's vertex numbers, three each); null when the brief has another vertex count. */
export function briefClothTriangles(vertexCount?: number): Uint32Array | null {
  const s = BRIEF_CLOTH_PROXY;
  if (vertexCount !== undefined && vertexCount !== s.vertices) return null;
  if (decoded) return decoded;
  const bin = globalThis.atob(s.data), out = new Uint32Array(s.triangles * 3);
  for (let i = 0; i < out.length; i++) out[i] = bin.charCodeAt(i * 2) | (bin.charCodeAt(i * 2 + 1) << 8);
  return (decoded = out);
}
`;
  writeFileSync(outFile, source);
  log(`wrote ${outFile}: ${tris.length / 3} triangles on ${points} points of the brief's ${n} (from ${body.length / 3}), error ${error.toFixed(5)}`);
}

if (process.argv[1]?.endsWith('briefCloth.mjs')) await briefCloth(process.argv[2], process.argv[3]);
