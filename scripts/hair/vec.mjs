/**
 * THE HAIR TOOLKIT'S NUMBERS: three-vectors as plain arrays, a seeded random, a spline. Taken as they were from the first
 * hairstyle's bake (`scripts/sarahV2Recovery/hair-bake.mjs`), operation for operation, so a style built on the toolkit
 * comes out to the same floats as that script did (the `ponytail` style is held to its file: `scripts/hair/bake.mjs`).
 */
export function mulberry32(seed) { let a = seed >>> 0; return () => { a = (a + 0x6d2b79f5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
export const add = (a, b) => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
export const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
export const mul = (a, s) => [a[0] * s, a[1] * s, a[2] * s];
export const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
export const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
export const len = (a) => Math.hypot(a[0], a[1], a[2]);
export const unit = (a) => { const l = len(a) || 1; return [a[0] / l, a[1] / l, a[2] / l]; };
export const lerp3 = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
export const clamp = (x, a, b) => Math.min(b, Math.max(a, x));
export const smoothstep = (e0, e1, x) => { const t = clamp((x - e0) / (e1 - e0), 0, 1); return t * t * (3 - 2 * t); };
/** Catmull-Rom through points, at u in [0, 1] over the whole run. */
export function catmull(points, u) {
  const n = points.length - 1, f = clamp(u, 0, 1) * n, i = Math.min(n - 1, Math.floor(f)), t = f - i;
  const p0 = points[Math.max(0, i - 1)], p1 = points[i], p2 = points[i + 1], p3 = points[Math.min(n, i + 2)];
  const t2 = t * t, t3 = t2 * t;
  return [0, 1, 2].map((k) => 0.5 * ((2 * p1[k]) + (-p0[k] + p2[k]) * t + (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * t2 + (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * t3));
}
/** Smooth a run of points in place (its ends held): `passes` times each point moved `amount` toward its neighbours' middle. */
export function relax(points, passes = 2, amount = 0.5) {
  for (let pass = 0; pass < passes; pass++) for (let k = 1; k < points.length - 1; k++) points[k] = lerp3(points[k], lerp3(points[k - 1], points[k + 1], 0.5), amount);
  return points;
}
